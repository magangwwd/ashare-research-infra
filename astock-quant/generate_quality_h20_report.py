"""
Generate an archived H20 quality report for:
- financial quality stocks (A/A+)
- strong historical performance
- LightGBM 20-day return prediction
- Kronos 20-day return prediction

The report is written under financial_data/reports/ and never overwrites an
existing report file. The Kronos input used here is generated by:
python -m kronos_return_top3 --predict-only --use-mini --hold-days 20 --full-universe --batch-size 32 --output-prefix mini_full_h20_lb512 --quiet
"""

from __future__ import annotations

from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd


BASE_DIR = Path(__file__).resolve().parent
SCORES_CSV = BASE_DIR / "financial_data" / "scores.csv"
MARKET_SIGNAL_CSV = BASE_DIR / "markov_strategy" / "output" / "latest_signal.csv"
DAILY_DATA_DIR = BASE_DIR / "daily_data"
QUALITY_UNIVERSE_CSV = BASE_DIR / "financial_data" / "kronos_h20_quality_universe.csv"
REPORT_DIR = BASE_DIR / "financial_data" / "reports"
LGBM_CSV = BASE_DIR / "lightgbm_return_top3" / "output" / "predictions_latest.csv"
KRONOS_H20_CSV = (
    BASE_DIR / "kronos_return_top3" / "output" / "mini_full_h20_lb512_predictions_latest.csv"
)


# ── 可信度权重（可通过 --kronos-weight 命令行覆盖） ──────────────────────────
_W_FINANCIAL: float = 0.25
_W_PAST: float = 0.20
_W_LGBM: float = 0.35
_W_KRONOS: float = 0.15
_W_AGREEMENT: float = 0.05
ENTRY_THRESHOLD: float = 72.0
WATCH_THRESHOLD: float = 60.0
OVERHEAT_20D_THRESHOLD: float = 0.25
MAX_TOP5_PER_INDUSTRY: int = 1

QUALITY_COLUMNS = ["ts_code", "name", "industry", "rating", "total_score", "ret_1y", "ret_6m", "ret_20d"]


def _load_market_signal() -> dict | None:
    """读取 latest_signal.csv，返回 dict 或 None（文件不存在/读取失败时静默跳过）。"""
    if not MARKET_SIGNAL_CSV.exists():
        return None
    try:
        df = pd.read_csv(MARKET_SIGNAL_CSV, encoding="utf-8-sig", nrows=1)
        if df.empty:
            return None
        row = df.iloc[0]
        return {
            "date": str(row.get("date", "")),
            "state": str(row.get("state", "")),
            "market_score": row.get("market_score", float("nan")),
            "action": str(row.get("action", "")),
            "exposure": float(row.get("exposure", 0.0)),
            "comment": str(row.get("comment", "")),
        }
    except Exception:
        return None


def _market_signal_lines(sig: dict, report_signal_date: str) -> list[str]:
    """把市场状态信号渲染为 Markdown 行块。"""
    action = sig["action"]
    exposure_pct = f"{sig['exposure']:.0%}"
    score = sig["market_score"]
    sig_date = sig["date"]

    stale_note = ""
    if sig_date != report_signal_date:
        stale_note = (
            f"\n\n> **注意**：市场信号日（{sig_date}）与本报告信号日（{report_signal_date}）"
            "不一致，请先更新 `daily_data` 并重新运行 `markov_strategy/walk_forward.py`。"
        )

    action_display = {
        "normal": "normal — 可正常执行个股策略",
        "reduce": "reduce — 建议仓位降至 50%，只选高置信标的",
        "no_trade": "no_trade — 建议暂停新开仓",
    }.get(action, action)

    lines = [
        "## 市场状态过滤器（Markov + 市场评分）",
        "",
        f"> 信号日：{sig_date}  |  状态：{sig['state']}  |  "
        f"市场评分：{score:.1f}/100  |  建议仓位：{exposure_pct}",
        "",
        f"**动作：{action_display}**",
        "",
        f"{sig['comment']}{stale_note}",
        "",
        "> 本模块（`markov_strategy/walk_forward.py`）独立生成，不影响下方个股评分和排名。",
        "",
        "---",
        "",
    ]
    return lines


def pct_rank(series: pd.Series) -> pd.Series:
    return series.rank(pct=True, method="average") * 100


def rank_fraction(rank: pd.Series, total: int) -> pd.Series:
    rank_num = pd.to_numeric(rank, errors="coerce")
    if total <= 0:
        return pd.Series(np.nan, index=rank.index)
    return rank_num / total


def rank_score_from_rank(rank: pd.Series, total: int) -> pd.Series:
    rank_num = pd.to_numeric(rank, errors="coerce")
    if total <= 0:
        return pd.Series(np.nan, index=rank.index)
    if total == 1:
        return pd.Series(np.where(rank_num.notna(), 100.0, np.nan), index=rank.index)
    return (100 * (1 - (rank_num - 1) / (total - 1))).clip(lower=0, upper=100)


def fmt_pct(value: float | int | None, digits: int = 1) -> str:
    if value is None or pd.isna(value):
        return "N/A"
    return f"{float(value) * 100:+.{digits}f}%"


def fmt_rank(rank: float | int | None, denom: int) -> str:
    if rank is None or pd.isna(rank):
        return "N/A"
    return f"{int(rank)}/{denom}"


def parse_schedule_flag(series: pd.Series) -> bool:
    values = {
        str(value).strip().lower()
        for value in series.dropna().unique()
    }
    if not values:
        raise ValueError("LightGBM 缺少 on_rebalance_schedule，无法判断是否可执行。")
    if not values <= {"true", "false"} or len(values) != 1:
        raise ValueError(f"LightGBM 调仓标记不一致: {sorted(values)}")
    return values == {"true"}


def select_diversified_top(
    candidates: pd.DataFrame,
    max_rows: int = 5,
    max_per_industry: int = MAX_TOP5_PER_INDUSTRY,
) -> pd.DataFrame:
    """按可信度排序，并限制 Top 列表中的单一行业集中度。"""
    ordered = candidates.sort_values(
        ["confidence", "kronos_score", "lgbm_score"],
        ascending=False,
    )
    selected: list[int] = []
    industry_counts: dict[str, int] = {}
    for idx, row in ordered.iterrows():
        industry = str(row.get("industry", "")).strip()
        industry_key = industry if industry and industry.lower() != "nan" else f"未知:{row['ts_code']}"
        if industry_counts.get(industry_key, 0) >= max_per_industry:
            continue
        selected.append(idx)
        industry_counts[industry_key] = industry_counts.get(industry_key, 0) + 1
        if len(selected) >= max_rows:
            break
    return ordered.loc[selected].reset_index(drop=True)


def next_report_path(report_date: str) -> Path:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    base_path = REPORT_DIR / f"report_{report_date}.md"
    if not base_path.exists():
        return base_path

    seq = 2
    while True:
        candidate = REPORT_DIR / f"report_{report_date}_{seq}.md"
        if not candidate.exists():
            return candidate
        seq += 1


def calc_return(ts_code: str, days: int, as_of_date: pd.Timestamp) -> float | None:
    path = DAILY_DATA_DIR / f"{ts_code}.csv"
    if not path.exists():
        return None
    try:
        df = pd.read_csv(path, usecols=["Date", "Close"], dtype={"Date": str, "Close": float})
        df = df.sort_values("Date")
        as_of = pd.Timestamp(as_of_date).strftime("%Y-%m-%d")
        df = df[df["Date"] <= as_of]
        cutoff = (pd.Timestamp(as_of_date) - timedelta(days=days)).strftime("%Y-%m-%d")
        past = df[df["Date"] <= cutoff]
        if past.empty or df.empty:
            return None
        start = past.iloc[-1]["Close"]
        end = df.iloc[-1]["Close"]
        return (end - start) / start if start > 0 else None
    except Exception:
        return None


def calc_recent_surge(
    ts_code: str,
    as_of_date: pd.Timestamp,
    days: int = 5,
) -> float | None:
    """返回近 days 个交易日的累计涨幅（用收盘价）。"""
    path = DAILY_DATA_DIR / f"{ts_code}.csv"
    if not path.exists():
        return None
    try:
        df = pd.read_csv(path, usecols=["Date", "Close"], dtype={"Date": str, "Close": float})
        df = df.sort_values("Date")
        as_of = pd.Timestamp(as_of_date).strftime("%Y-%m-%d")
        df = df[df["Date"] <= as_of]
        recent = df.tail(days + 1)
        if len(recent) < 2:
            return None
        start = recent.iloc[0]["Close"]
        end = recent.iloc[-1]["Close"]
        return (end - start) / start if start > 0 else None
    except Exception:
        return None


def build_quality_universe(
    scores: pd.DataFrame,
    as_of_date: pd.Timestamp,
) -> pd.DataFrame:
    quality = scores[scores["rating"].isin(["A+", "A"])].copy()
    if quality.empty:
        result = pd.DataFrame(columns=QUALITY_COLUMNS)
        result.to_csv(QUALITY_UNIVERSE_CSV, index=False, encoding="utf-8-sig")
        return result

    returns = quality["ts_code"].apply(
        lambda code: pd.Series(
            {
                "ret_1y": calc_return(str(code), 365, as_of_date),
                "ret_6m": calc_return(str(code), 180, as_of_date),
                "ret_20d": calc_return(str(code), 20, as_of_date),
            }
        )
    )
    quality = pd.concat([quality.reset_index(drop=True), returns.reset_index(drop=True)], axis=1)
    quality = quality[
        (quality["ret_1y"].notna())
        & (quality["ret_6m"].notna())
        & (quality["ret_1y"] > 0.20)
        & (quality["ret_6m"] > 0)
    ].copy()
    quality = quality.sort_values(["total_score", "ret_1y"], ascending=False)
    result = quality[QUALITY_COLUMNS].reset_index(drop=True)
    result.to_csv(QUALITY_UNIVERSE_CSV, index=False, encoding="utf-8-sig")
    return result


def reason(row: pd.Series) -> str:
    kronos_pred = row.get("kronos_pred")
    if pd.isna(kronos_pred):
        model_text = "Kronos未刷新，本期仅LightGBM临时评分"
    elif row["lgbm_pred"] > 0 and kronos_pred > 0:
        model_text = "双模型均为正"
    else:
        model_text = "模型分歧，需等待确认"
    details = (
        f"财务{row['rating']}、得分{row['total_score']:.1f}；"
        f"1Y {fmt_pct(row['ret_1y'])} / 6M {fmt_pct(row['ret_6m'])}；"
        f"{model_text}"
    )
    if row.get("is_overheated", False):
        details += f"；20D {fmt_pct(row['ret_20d'])}，短线过热"
    return details


def table_lines(df: pd.DataFrame, lgbm_total: int, kronos_total: int, max_rows: int | None = None) -> list[str]:
    if max_rows is not None:
        df = df.head(max_rows)

    lines = [
        "| 排名 | 可信度 | 分层 | 代码 | 名称 | 行业 | 评级/财务分 | 1Y | 6M | 20D | LightGBM 20日 | Kronos 20日 | 理由 |",
        "|----:|------:|------|------|------|------|------------|----:|----:|----:|-------------|------------|------|",
    ]
    if df.empty:
        lines.append(
            "| - | - | - | - | - | - | - | - | - | - | - | - | 当前没有股票满足该层级条件。 |"
        )
        return lines

    for rank, (_, row) in enumerate(df.iterrows(), start=1):
        lines.append(
            f"| {rank} | {row['confidence']:.1f} | {row['action']} | {row['ts_code']} | "
            f"{row['name']} | {row['industry']} | {row['rating']}/{row['total_score']:.1f} | "
            f"{fmt_pct(row['ret_1y'])} | {fmt_pct(row['ret_6m'])} | {fmt_pct(row['ret_20d'])} | "
            f"{fmt_pct(row['lgbm_pred'])}（{fmt_rank(row['lgbm_rank'], lgbm_total)}） | "
            f"{fmt_pct(row['kronos_pred'])}（{fmt_rank(row['kronos_rank'], kronos_total)}） | "
            f"{row['reason']} |"
        )
    return lines


def _build_news_research_appendix(top5_df: pd.DataFrame) -> list[str]:
    """Fetch news and research for top-5 stocks and return Markdown lines.

    Requires a_stock_data (available in .venv-data-source).
    Returns an empty list if the module is not importable or any fetch fails
    entirely — the main report is never blocked by this function.

    First run per stock is slow (~20s news + ~45s research uncached);
    subsequent runs use the 24h disk cache and take <1s.
    """
    try:
        from a_stock_data import AStockDataClient  # noqa: PLC0415
    except ImportError:
        return [
            "",
            "## 附录：近期要闻与研报参考",
            "",
            "> `a_stock_data` 模块未安装，跳过附录。"
            "在 `.venv-data-source` 虚拟环境中运行可启用此功能。",
            "",
        ]

    client = AStockDataClient(cache_ttl_hours=24, research_max_rows=50)
    lines: list[str] = [
        "",
        "## 附录：近期要闻与研报参考（只读辅助）",
        "",
        "> 数据来源：akshare（新闻 / 研报元数据）。"
        "以下内容仅供参考，**不影响上方评分和排名**。",
        "> 研报按发布日期从新到旧排列；信号日之后发布的研报不应用于当前预测，仅供背景参考。",
        "",
    ]

    name_map: dict[str, str] = {}
    if "name" in top5_df.columns:
        name_map = dict(zip(top5_df["ts_code"], top5_df["name"]))

    for ts_code in top5_df["ts_code"].tolist():
        display = f"{ts_code} {name_map.get(ts_code, '')}".strip()
        lines.append(f"### {display}")
        lines.append("")

        # ── News ──────────────────────────────────────────────────────
        try:
            news_df = client.get_stock_news(ts_code)
            if not news_df.empty:
                lines += [
                    "**近期新闻（最新 5 条）**",
                    "",
                    "| 发布时间 | 标题 | 来源 |",
                    "|----------|------|------|",
                ]
                for _, row in news_df.head(5).iterrows():
                    title = str(row.get("新闻标题", "")).replace("|", "/")[:60]
                    src = str(row.get("文章来源", "")).replace("|", "/")[:20]
                    ts = str(row.get("发布时间", ""))[:16]
                    link = str(row.get("新闻链接", ""))
                    title_cell = f"[{title}]({link})" if link and link != "nan" else title
                    lines.append(f"| {ts} | {title_cell} | {src} |")
                lines.append("")
        except Exception as exc:
            lines += [f"> 新闻获取失败：{exc!s:.80}", ""]

        # ── Research ───────────────────────────────────────────────────
        try:
            res_df = client.get_research_reports(ts_code)
            if not res_df.empty:
                lines += [
                    "**研报摘要（最新 3 篇）**",
                    "",
                    "| 日期 | 报告名称 | 机构 | 评级 | PDF |",
                    "|------|----------|------|------|-----|",
                ]
                for _, row in res_df.head(3).iterrows():
                    date = str(row.get("日期", ""))[:10]
                    rname = str(row.get("报告名称", "")).replace("|", "/")[:50]
                    inst = str(row.get("机构", "")).replace("|", "/")[:20]
                    rating = str(row.get("东财评级", "")).replace("|", "/")[:10]
                    pdf = str(row.get("报告PDF链接", ""))
                    pdf_cell = f"[PDF]({pdf})" if pdf and pdf != "nan" else "—"
                    lines.append(f"| {date} | {rname} | {inst} | {rating} | {pdf_cell} |")
                lines.append("")
        except Exception as exc:
            lines += [f"> 研报获取失败：{exc!s:.80}", ""]

    return lines


def main() -> None:
    import argparse as _ap
    _parser = _ap.ArgumentParser(description="Generate H20 quality report")
    _parser.add_argument(
        "--kronos-weight", type=float, default=None,
        help="覆盖 Kronos 权重 (0~0.50)，LightGBM 自动调整为 0.50 - kronos_weight",
    )
    _parser.add_argument(
        "--with-news-appendix", action="store_true", default=False,
        help="在报告末尾追加 Top-5 股票的近期新闻和研报摘要（需要 a_stock_data 模块）",
    )
    _parser.add_argument(
        "--allow-lgbm-only", action="store_true", default=False,
        help="当 Kronos 信号日落后时生成 LightGBM-only 临时报告；默认仍要求双模型同日。",
    )
    _args = _parser.parse_args()

    w_kronos = _W_KRONOS
    w_lgbm = _W_LGBM
    if _args.kronos_weight is not None:
        kw = float(_args.kronos_weight)
        if not (0.0 <= kw <= 0.50):
            raise ValueError(f"--kronos-weight 须在 [0, 0.50]，实际 {kw}")
        w_kronos = kw
        w_lgbm = 0.50 - kw

    scores = pd.read_csv(SCORES_CSV, encoding="utf-8-sig")
    lgbm_raw = pd.read_csv(
        LGBM_CSV,
        encoding="utf-8-sig",
        usecols=[
            "ts_code",
            "prediction",
            "prediction_rank",
            "signal_date",
            "on_rebalance_schedule",
        ],
    )
    kronos_raw = pd.read_csv(
        KRONOS_H20_CSV,
        encoding="utf-8-sig",
        usecols=["ts_code", "predicted_return", "prediction_rank", "signal_date"],
    )

    lgbm_date = str(lgbm_raw["signal_date"].dropna().iloc[0]) if not lgbm_raw.empty else "未知"
    kronos_date = str(kronos_raw["signal_date"].dropna().iloc[0]) if not kronos_raw.empty else "未知"
    if lgbm_date == "未知" or kronos_date == "未知":
        raise ValueError("LightGBM 或 Kronos 缺少 signal_date，无法确定报告交易日。")
    lgbm_only_mode = False
    if lgbm_date != kronos_date:
        if not _args.allow_lgbm_only:
            raise ValueError(
                f"双模型信号日不一致：LightGBM={lgbm_date}, Kronos={kronos_date}"
            )
        lgbm_only_mode = True
        w_kronos = 0.0
        w_lgbm = 0.50
    signal_date = pd.Timestamp(lgbm_date)
    report_date = signal_date.strftime("%Y-%m-%d")
    on_rebalance_schedule = parse_schedule_flag(lgbm_raw["on_rebalance_schedule"])
    market_sig = _load_market_signal()
    market_blocks_new_positions = (
        market_sig is not None
        and str(market_sig.get("date", "")) == report_date
        and str(market_sig.get("action", "")).strip().lower() == "no_trade"
    )
    quality = build_quality_universe(scores, as_of_date=signal_date)

    lgbm = lgbm_raw.rename(
        columns={"prediction": "lgbm_pred", "prediction_rank": "lgbm_rank"}
    )[["ts_code", "lgbm_pred", "lgbm_rank"]]
    kronos = kronos_raw.rename(
        columns={"predicted_return": "kronos_pred", "prediction_rank": "kronos_rank"}
    )[["ts_code", "kronos_pred", "kronos_rank"]]

    if lgbm_only_mode:
        kronos = pd.DataFrame(
            {
                "ts_code": lgbm["ts_code"],
                "kronos_pred": np.nan,
                "kronos_rank": np.nan,
            }
        )
    cand = quality.merge(lgbm, on="ts_code", how="inner").merge(kronos, on="ts_code", how="inner")

    # 近5日异常波动过滤：剔除累计涨幅>20%的股票，避免追高
    cand["surge_5d"] = cand["ts_code"].apply(
        lambda c: calc_recent_surge(str(c), as_of_date=signal_date, days=5)
    )
    surge_mask = cand["surge_5d"].fillna(0) > 0.20
    surge_filtered = cand[surge_mask][["ts_code", "name", "surge_5d"]].copy()
    if not surge_filtered.empty:
        details = ", ".join(
            f"{r.ts_code} {r.name}({r.surge_5d * 100:+.0f}%)"
            for _, r in surge_filtered.iterrows()
        )
        print(f"  [异常波动过滤] 剔除 {len(surge_filtered)} 只近5日涨幅>20%：{details}")
    cand = cand[~surge_mask].reset_index(drop=True)
    surge_filtered_count = len(surge_filtered)

    universe_total = len(scores)
    lgbm_total = len(lgbm)
    kronos_total = len(kronos)
    aa_count = int(scores["rating"].isin(["A+", "A"]).sum())
    quality_count = len(quality)

    cand["financial_score"] = pct_rank(cand["total_score"])
    cand["past_score"] = (
        0.45 * pct_rank(cand["ret_1y"])
        + 0.40 * pct_rank(cand["ret_6m"])
        + 0.15 * pct_rank(cand["ret_20d"].fillna(cand["ret_20d"].median()))
    )
    cand["lgbm_pct"] = rank_fraction(cand["lgbm_rank"], lgbm_total)
    cand["lgbm_rank_score"] = rank_score_from_rank(cand["lgbm_rank"], lgbm_total)
    cand["lgbm_ret_score"] = ((cand["lgbm_pred"].clip(-0.05, 0.15) + 0.05) / 0.20) * 100
    cand["lgbm_score"] = 0.70 * cand["lgbm_rank_score"] + 0.30 * cand["lgbm_ret_score"]
    if lgbm_only_mode:
        cand["kronos_pct"] = np.nan
        cand["kronos_rank_score"] = 0.0
        cand["kronos_ret_score"] = 0.0
        cand["kronos_score"] = 0.0
        cand["agreement_score"] = np.where(cand["lgbm_pred"] > 0, 60, 20)
    else:
        cand["kronos_pct"] = rank_fraction(cand["kronos_rank"], kronos_total)
        cand["kronos_rank_score"] = rank_score_from_rank(cand["kronos_rank"], kronos_total)
        cand["kronos_ret_score"] = ((cand["kronos_pred"].clip(-0.05, 0.15) + 0.05) / 0.20) * 100
        cand["kronos_score"] = 0.70 * cand["kronos_rank_score"] + 0.30 * cand["kronos_ret_score"]
        cand["agreement_score"] = np.select(
            [
                (cand["lgbm_pred"] > 0) & (cand["kronos_pred"] > 0),
                (cand["lgbm_pred"] > 0) | (cand["kronos_pred"] > 0),
            ],
            [100, 60],
            default=20,
        )
    cand["confidence"] = (
        _W_FINANCIAL  * cand["financial_score"]
        + _W_PAST     * cand["past_score"]
        + w_lgbm      * cand["lgbm_score"]
        + w_kronos    * cand["kronos_score"]
        + _W_AGREEMENT * cand["agreement_score"]
    )

